// Khandan 12 in the book's index: اولاد سید عبدالواسع بن شاہ سید ابوالحسن
//
// Seven photos, book pages 72–78 (the photo file order is the page order). Each page's heading
// "صفحہ N سید X بن سید Y" says whose family it draws and which page it continues from:
//   page 72  سید عبدالواسع بن شاہ سید ابوالحسن (from page 30)
