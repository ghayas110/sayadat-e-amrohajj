// The whole khandan hangs from one tree on p86 (سید مبارک بن سید منتجب ثانی, "صفحہ 22"); the families the
// book continues on pp87-90 are written as consts above it and attached with onPage().
//
// Conventions used here
//  - Where a bar of children wraps onto a second or third bar, the children are listed row by row, each row right
//    to left (the first bar nearest the parent first).
//  - Unnamed daughters are written as f('دختر', husband, mohalla).
//  - Names without "سید" under the box are treated as daughters; names with "سید" as sons.
//  - Pen crosses and circled reader's marks (①) are ignored.
//  - Families the book continues on pages that are not among the photos are stubs: عبدالجلیل (p117),
//    عبدالمجید (p131), ہزبر علی (p92), عبدالماجد (p91, khandan 20 holds it).

