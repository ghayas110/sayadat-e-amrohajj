// Kausar-ul-Ansab (1999), pages 287–295: محلہ نخشبی
// Khandan 46 in the book's index: اولاد سید خواجہ بزرگ بن خواجہ سید خطیر ثانی
//
// Nine photos, book pages 287–295 (photo order = page order). The page numbers were checked
// against the photos' own headers and agree with the index (khandan 45 starts on 283, khandan 47
// on 296).
//
// NOTE on the mohalla: every page of this khandan is headed محلہ نخشبی, but `amrohaIndex.ts`
// lists the khandan under the value 'Bakhshi' with the Urdu label محلہ بخشی — a misreading of
// نخشبی. 'Bakhshi' is kept here because it is the stored value the index defines, and no other
// khandan uses it; the Urdu label in the index has been corrected to محلہ نخشبی.
//
// Page 287 opens with the line of descent, drawn as one chain of arrows rather than as a tree:
//   حضرت امام علی نقی علیہ السلام ← عبداللہ ← علی اکبر ← حسین ← محمد ← سعید ← ابراہیم ← سمعان ←
//   ناصر الدین ابو یوسف ← خواجہ ابوالقاسم ← اسعد اللہ ← عبد المقتدر ← قطب الدین محمد ←
//   رکن الدین حسن ← خواجہ احمد مودود ← خواجہ قطب الدین مودود ← خواجہ خطیر ← مودود ثانی ←
//   خواجہ سعید ← خواجہ عثمان ← خواجہ محمود ← خواجہ خطیر ثانی ← خواجہ میراں بزرگ
// That chain is the khandan's ancestry, not a set of families, so it is kept here as a note and the
// tree starts at خواجہ میراں بزرگ with خواجہ خطیر ثانی as his father.
//
// Page 287 is a ten-generation chart of single sons with almost no daughters; the columns run into
// one another and a good many of the joins are marked VERIFY.
//
//   page 287  سید خواجہ میراں بزرگ بن خواجہ سید خطیر ثانی
//   page 288  سید عارف علی بن سید قطب الدین (from 287)
//   page 289  سید خادم علی بن سید ولایت علی (from 288)
//   page 290  سید خیر علی بن سید نجابت علی (from 288)
//   page 291  three charts, all "صفحہ ۲۹۰": سید نذیر احمد / سید معصوم احمد / سید مقبول احمد،
//             each بن سید آل محمد
//   page 292  سید علی محمد بن سید ابو محمد (from 287)
//   page 293  سید محمد بخش بن سید علی احمد (from 292) and سید بشیر حسن بن سید علی حسن (from 287)
//   page 294  سید بہادر علی بن سید رستم علی (from 287) and
//             سید خواجہ احمد عرف کمالے بن سید خواجہ میراں بزرگ (from 287)
//   page 295  سید مہدی حسن بن سید علی حسن (from 294)، سید سعید حسن بن سید حسین بخش (from 294)،
//             and سید ماہر حسن / سید ذاکر حسن، both بن سید مظاہر حسن (same page)
//
// Pages 290–295 are the densest in the khandan and two of the photos (290, 293) are the softest,
// so the joins marked VERIFY there are worth a second pass against the book.
//
// Children are listed eldest first = right to left in the book. Circled ①-type reader's marks are
// ignored.

